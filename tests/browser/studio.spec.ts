test('silent motion preview produces a real WebM file', async ({ page }) => {
  await page.goto('/')
  const downloaded = page.waitForEvent('download', { timeout: 30_000 })
  await page.getByRole('button', { name: 'Export silent preview', exact: true }).click()
  const file = await downloaded
  expect(file.suggestedFilename()).toMatch(/silent-preview\.webm$/)
  const bytes = await readFile((await file.path())!)
  expect(bytes.subarray(0, 4).toString('hex')).toBe('1a45dfa3')
  expect(bytes.byteLength).toBeGreaterThan(10000)
})
